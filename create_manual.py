def generate_manual(output_path: Path) -> None:
    app = QApplication.instance() or QApplication([])

    doc = QTextDocument()
    doc.setHtml(HTML % {"version": VERSION})
    doc.setPageSize(QSizeF(595, 842))  # A4

    writer = QPdfWriter(str(output_path))
    writer.setPageSize(QPageSize(QPageSize.A4))
    writer.setResolution(96)
    writer.setPageMargins(QMarginsF(25, 25, 25, 25), QPageLayout.Unit.Millimeter)

    doc.print_(writer)
    print(f"Manual created: {output_path}")


if __name__ == "__main__":
    out = Path(__file__).parent / "finaltime" / "assets" / "manual.pdf"
    out.parent.mkdir(parents=True, exist_ok=True)
    generate_manual(out)
